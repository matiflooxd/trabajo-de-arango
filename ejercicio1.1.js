
// ---------- Ejercicio 1.1 — Declaración de variables ----------
console.log("--- Ejercicio 1.1 ---");
var nombre = "Ana";        // var: alcance de función, se puede redeclarar (hoy se evita)
let edad = 25;             // let: alcance de bloque, se puede reasignar
const ciudad = "Medellín"; // const: alcance de bloque, NO se puede reasignar
console.log("Mi nombre (var) es:", nombre);
console.log("Mi edad (let) es:", edad);
console.log("Mi ciudad (const) es:", ciudad);